#!/usr/bin/env python3
"""Sync the profile README with damnz-dev/writeups.

Reads writeups/index.json (generated by that repo's CI) and rewrites:
  - README.md          -> block between <!-- WRITEUPS:START --> / <!-- WRITEUPS:END -->
  - assets/casefiles.svg -> archive card with live per-category counts
"""
import json
import pathlib
import re
import urllib.parse
import urllib.request
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
INDEX_URL = "https://raw.githubusercontent.com/damnz-dev/writeups/main/index.json"
REPO_URL = "https://github.com/damnz-dev/writeups"
LATEST = 5
BG = "0b1117"

CATEGORIES = {
    "machines":  ("Machines",  "#5eead4"),
    "web":       ("Web",       "#38bdf8"),
    "pwn":       ("Pwn",       "#f87171"),
    "crypto":    ("Crypto",    "#a78bfa"),
    "rev":       ("Reversing", "#fbbf24"),
    "forensics": ("Forensics", "#34d399"),
    "misc":      ("Misc",      "#94a3b8"),
}
DIFFICULTY = {"easy": "22c55e", "medium": "f59e0b", "hard": "ef4444", "insane": "a855f7"}


def esc(text: str) -> str:
    return urllib.parse.quote(str(text).replace("-", "--").replace("_", "__").replace(" ", "_"))


def badge(message: str, color: str) -> str:
    return f"https://img.shields.io/badge/{esc(message)}-{color}?style=flat-square&labelColor={BG}"


def render_table(entries: list[dict]) -> str:
    latest = list(reversed(entries))[:LATEST]
    head = "| # | Case | Category | Difficulty | Link |\n|:-:|:-----|:--------:|:----------:|:----:|"
    if not latest:
        return head + "\n| — | _No case files yet_ | | | |"
    rows = []
    for e in latest:
        name, color = CATEGORIES.get(e["category"], (e["category"], "#94a3b8"))
        diff = e.get("difficulty", "unrated")
        title = f"**{e['title']}**" + (f"<br><sub>{e['subtitle']}</sub>" if e.get("subtitle") else "")
        rows.append(
            f"| `{e['id']}` | {title} "
            f"| <img src=\"{badge(name, color.lstrip('#'))}\" alt=\"{name}\"/> "
            f"| <img src=\"{badge(diff.title(), DIFFICULTY.get(diff, '475569'))}\" alt=\"{diff}\"/> "
            f"| [`↗`]({e['url']}) |"
        )
    return head + "\n" + "\n".join(rows)


def render_card(total: int, counts: dict) -> str:
    """Archive card: one bar per populated category, width proportional to count."""
    active = [(k, v) for k, v in CATEGORIES.items() if counts.get(k, 0) > 0]
    if not active:
        active = [("machines", CATEGORIES["machines"])]
    w, row_h, top = 900, 28, 78
    h = top + row_h * len(active) + 24
    peak = max([1, *counts.values()])
    bars = []
    for i, (key, (name, color)) in enumerate(active):
        n = counts.get(key, 0)
        y = top + i * row_h
        bar_w = 0 if n == 0 else max(8, int(560 * n / peak))
        bars.append(
            f'<text x="40" y="{y + 13}" fill="#94a3b8">{escape(name)}</text>'
            f'<rect x="170" y="{y + 2}" width="560" height="14" rx="3" fill="#111a22"/>'
            + (f'<rect x="170" y="{y + 2}" width="{bar_w}" height="14" rx="3" fill="{color}" fill-opacity="0.85">'
               f'<animate attributeName="width" from="0" to="{bar_w}" dur="1.2s" fill="freeze"/></rect>' if n else "")
            + f'<text x="{w - 40}" y="{y + 13}" text-anchor="end" fill="{color if n else "#475569"}">{n:02d}</text>'
        )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-label="Case files: {total}">
  <defs><pattern id="g" width="24" height="24" patternUnits="userSpaceOnUse"><path d="M24 0H0V24" fill="none" stroke="#5eead4" stroke-opacity="0.05"/></pattern></defs>
  <rect width="{w}" height="{h}" rx="10" fill="#0b1117"/><rect width="{w}" height="{h}" rx="10" fill="url(#g)"/>
  <rect x="0.5" y="0.5" width="{w - 1}" height="{h - 1}" rx="10" fill="none" stroke="#1f2a33"/>
  <g font-family="Consolas, 'Courier New', monospace" font-size="13">
    <text x="40" y="38" fill="#5eead4" letter-spacing="2" font-size="12">ARCHIVE // CASE FILES</text>
    <text x="40" y="60" fill="#e2e8f0" font-size="18" font-weight="700">{total:02d} documented</text>
    <text x="{w - 40}" y="38" text-anchor="end" fill="#64748b" font-size="12" letter-spacing="2">AUTO-SYNCED</text>
    {''.join(bars)}
  </g>
</svg>
"""


def main() -> None:
    with urllib.request.urlopen(INDEX_URL, timeout=20) as resp:
        data = json.load(resp)
    entries, counts = data.get("entries", []), data.get("counts", {})

    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    text = re.sub(
        r"(<!-- WRITEUPS:START -->).*?(<!-- WRITEUPS:END -->)",
        lambda m: f"{m.group(1)}\n{render_table(entries)}\n{m.group(2)}",
        text, flags=re.S,
    )
    readme.write_text(text, encoding="utf-8")
    (ROOT / "assets" / "casefiles.svg").write_text(render_card(data.get("total", len(entries)), counts), encoding="utf-8")
    print(f"synced {len(entries)} writeup(s)")


if __name__ == "__main__":
    main()
